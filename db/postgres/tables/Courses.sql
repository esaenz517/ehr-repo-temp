--Course Table
-- Each course offering belongs to one department (shared courses belong to IHS).
CREATE TABLE IF NOT EXISTS dbo.Courses (
    CourseId      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SubjectCode   VARCHAR(10)  NOT NULL,           -- 'PHAR', 'IHS'
    CourseNumber  VARCHAR(10)  NOT NULL,           -- '5310'
    Title         VARCHAR(200) NOT NULL,           -- 'Pharmacotherapy I'
    Term          VARCHAR(10)  NOT NULL,           -- 'Fall', 'Spring', 'Summer'
    TermYear      INT          NOT NULL,           -- 2026
    DepartmentId  INT          NOT NULL
        CONSTRAINT FK_Courses_Departments REFERENCES dbo.Departments(DepartmentId),
    IsActive      BOOLEAN      NOT NULL DEFAULT TRUE, -- hide past terms from the student dropdown
    CreatedAt     TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),

    CONSTRAINT CK_Courses_Term
        CHECK (Term IN ('Fall', 'Spring', 'Summer')),

    CONSTRAINT UQ_Courses_Offering
        UNIQUE (SubjectCode, CourseNumber, Term, TermYear)
);

-- COURSE DATA: each course's department comes from its subject code
INSERT INTO dbo.Courses (SubjectCode, CourseNumber, Title, Term, TermYear, DepartmentId, IsActive)
SELECT c.SubjectCode, c.CourseNumber, c.Title, c.Term, c.TermYear, d.DepartmentId, c.IsActive
FROM (
    VALUES
        (1, 'PHAR', '5310', 'Pharmacotherapy I',               'Fall',   2026, TRUE),
        (2, 'IHS',  '5100', 'Interprofessional Case Lab',      'Fall',   2026, TRUE),
        (3, 'PHAR', '5320', 'Pharmacotherapy II',              'Fall',   2026, TRUE),
        (4, 'PHAR', '6150', 'Medication Therapy Management',   'Fall',   2026, TRUE),
        (5, 'NURS', '3310', 'Adult Health Nursing I',          'Fall',   2026, TRUE),
        (6, 'OT',   '5150', 'Occupational Therapy Evaluation', 'Fall',   2026, TRUE),
        (7, 'PT',   '6210', 'Musculoskeletal Rehabilitation',  'Fall',   2026, TRUE),
        (8, 'PHAR', '5310', 'Pharmacotherapy I',               'Spring', 2026, FALSE)
) AS c (Seq, SubjectCode, CourseNumber, Title, Term, TermYear, IsActive)
JOIN dbo.Departments d ON d.Code = c.SubjectCode
ORDER BY c.Seq
ON CONFLICT ON CONSTRAINT UQ_Courses_Offering DO NOTHING;
