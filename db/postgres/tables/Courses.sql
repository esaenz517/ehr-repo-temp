--Course Table
CREATE TABLE IF NOT EXISTS dbo.Courses (
    CourseId      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SubjectCode   VARCHAR(10)  NOT NULL,           -- 'PHAR', 'IHS'
    CourseNumber  VARCHAR(10)  NOT NULL,           -- '5310'
    Title         VARCHAR(200) NOT NULL,           -- 'Pharmacotherapy I'
    Term          VARCHAR(10)  NOT NULL,           -- 'Fall', 'Spring', 'Summer'
    TermYear      INT          NOT NULL,           -- 2026
    IsActive      BOOLEAN      NOT NULL DEFAULT TRUE, -- hide past terms from the student dropdown
    CreatedAt     TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),

    CONSTRAINT CK_Courses_Term
        CHECK (Term IN ('Fall', 'Spring', 'Summer')),

    CONSTRAINT UQ_Courses_Offering
        UNIQUE (SubjectCode, CourseNumber, Term, TermYear)
);

