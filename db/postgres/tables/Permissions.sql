-- PERMISSIONS
-- Permission definitions are seeded here so all development environments
-- use the same permission codes. Role assignments can be changed separately.
CREATE TABLE IF NOT EXISTS dbo.Permissions (
    PermissionId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PermissionCode VARCHAR(150) NOT NULL UNIQUE,

    ResourceType VARCHAR(100) NOT NULL,
    Action VARCHAR(50) NOT NULL,

    RequiredDiscipline VARCHAR(100) NULL,
    SensitivityLevel VARCHAR(100) NULL,
    NoteTypeRestriction VARCHAR(100) NULL,
    CareContext VARCHAR(50) NULL,

    IsActive BOOLEAN NOT NULL DEFAULT TRUE
);

