CREATE TABLE IF NOT EXISTS dbo.NoteAuditEvents (
    AuditEventId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    NoteId INT NOT NULL
        REFERENCES dbo.ClinicalNotes(NoteId),

    ActorUserId INT NOT NULL
        REFERENCES dbo.Users(UserId),

    Action VARCHAR(50) NOT NULL,

    AddendumId INT NULL
        REFERENCES dbo.NoteAddenda(AddendumId),

    Details VARCHAR(1000) NULL,

    CreatedAt TIMESTAMP NOT NULL
        DEFAULT (now() AT TIME ZONE 'utc'),

    CONSTRAINT CK_NoteAuditEvents_Action
        CHECK (Action IN (
            'note_created',
            'note_updated',
            'note_approved',
            'addendum_created',
            'note_archived'
        ))
);

CREATE INDEX IF NOT EXISTS IX_NoteAuditEvents_Note
    ON dbo.NoteAuditEvents(NoteId, CreatedAt);
