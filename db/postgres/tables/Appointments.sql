-- APPOINTMENTS TABLE
CREATE TABLE IF NOT EXISTS dbo.Appointments (
    AppointmentId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PatientId INT NOT NULL,
    ProviderId INT NOT NULL,
    AppointmentDateTime TIMESTAMP NOT NULL,

    Location VARCHAR(200) NOT NULL,

    Status VARCHAR(50) NOT NULL
        DEFAULT 'scheduled'
        CHECK (Status IN (
            'scheduled',
            'completed',
            'cancelled'
        )),

    CONSTRAINT FK_Appointments_Patients
        FOREIGN KEY (PatientId)
        REFERENCES dbo.Patients(PatientId),

    CONSTRAINT FK_Appointments_Providers
        FOREIGN KEY (ProviderId)
        REFERENCES dbo.Providers(ProviderId)
);
