-- One row per deletion attempt: every DELETE request the API receives (whatever
-- its outcome) plus confirmations the user cancelled in the browser.
-- ActorUserId/ActorUsername have no foreign keys on purpose, so the log row is
-- always written, even for unknown users or after an account is removed.
CREATE TABLE IF NOT EXISTS dbo.DeletionAuditLog (
    DeletionAuditId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OccurredAt TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    ActorUserId INT NULL,
    ActorUsername VARCHAR(254) NULL,
    Resource VARCHAR(200) NOT NULL,
    ResourceId VARCHAR(100) NULL,
    RequestPath VARCHAR(500) NOT NULL,
    Outcome VARCHAR(20) NOT NULL,
    StatusCode INT NULL,
    ClientIp VARCHAR(64) NULL,
    Details VARCHAR(1000) NULL,

    CONSTRAINT CK_DeletionAuditLog_Outcome
        CHECK (Outcome IN (
            'deleted',
            'cancelled',
            'denied',
            'not_found',
            'conflict',
            'rejected',
            'error'
        ))
);

CREATE INDEX IF NOT EXISTS IX_DeletionAuditLog_OccurredAt
    ON dbo.DeletionAuditLog(OccurredAt);

CREATE INDEX IF NOT EXISTS IX_DeletionAuditLog_Resource
    ON dbo.DeletionAuditLog(Resource, ResourceId);
