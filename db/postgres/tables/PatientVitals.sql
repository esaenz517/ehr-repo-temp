CREATE TABLE IF NOT EXISTS dbo.PatientVitals (
    VitalId          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PatientId        INT NOT NULL REFERENCES dbo.Patients(PatientId),
    RecordedAt       TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    BloodPressure    VARCHAR(40) NULL,
    HeartRate        INT NULL,
    RespiratoryRate  INT NULL,
    TemperatureC     DECIMAL(5,2) NULL,
    OxygenSaturation DECIMAL(5,2) NULL,
    HeightCm         DECIMAL(7,2) NULL,
    WeightKg         DECIMAL(7,2) NULL
);
