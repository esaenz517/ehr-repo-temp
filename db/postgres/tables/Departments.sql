-- DEPARTMENTS
-- Academic departments. Each person (dbo.Staff) and each course (dbo.Courses)
-- belongs to one. Interprofessional courses belong to IHS.
CREATE TABLE IF NOT EXISTS dbo.Departments (
    DepartmentId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Code         VARCHAR(10)  NOT NULL CONSTRAINT UQ_Departments_Code UNIQUE,
    Name         VARCHAR(150) NOT NULL,
    IsActive     BOOLEAN      NOT NULL DEFAULT TRUE
);

INSERT INTO dbo.Departments (Code, Name) VALUES
    ('PHAR', 'Pharmacy'),
    ('NURS', 'Nursing'),
    ('PT',   'Physical Therapy'),
    ('OT',   'Occupational Therapy'),
    ('IHS',  'Interprofessional Health Sciences')
ON CONFLICT (Code) DO NOTHING;
