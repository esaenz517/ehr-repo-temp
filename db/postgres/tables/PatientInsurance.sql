CREATE TABLE IF NOT EXISTS dbo.PatientInsurance (
    InsuranceId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    PatientId INT NOT NULL,

    InsuranceCompany VARCHAR(150) NOT NULL,
    MemberId VARCHAR(100) NOT NULL,
    GroupNumber VARCHAR(100) NULL,

    PolicyholderName VARCHAR(200) NOT NULL,
    PolicyholderDateOfBirth DATE NULL,

    InsurancePriority VARCHAR(20) NOT NULL
        CHECK (InsurancePriority IN ('primary', 'secondary')),

    CoverageStartDate DATE NULL,
    CoverageEndDate DATE NULL,

    VerificationStatus VARCHAR(30) NOT NULL
        DEFAULT 'unverified'
        CHECK (VerificationStatus IN (
            'unverified',
            'verified_active',
            'verified_inactive',
            'unable_to_verify'
        )),

    CONSTRAINT FK_PatientInsurance_Patients
        FOREIGN KEY (PatientId)
        REFERENCES dbo.Patients(PatientId),

    CONSTRAINT CK_PatientInsurance_CoverageDates
        CHECK (
            CoverageStartDate IS NULL
            OR CoverageEndDate IS NULL
            OR CoverageEndDate >= CoverageStartDate
        )
);
