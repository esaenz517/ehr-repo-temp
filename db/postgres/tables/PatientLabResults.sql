CREATE TABLE IF NOT EXISTS dbo.PatientLabResults (
    LabResultId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PatientId   INT NOT NULL REFERENCES dbo.Patients(PatientId),
    TestName    VARCHAR(200) NOT NULL,
    Result      VARCHAR(200) NOT NULL,
    Unit        VARCHAR(50) NULL,
    Flag        VARCHAR(40) NULL,
    CollectedAt TIMESTAMP NOT NULL
);
