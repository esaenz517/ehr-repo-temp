CREATE TABLE IF NOT EXISTS dbo.NoteAddenda (
    AddendumId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    NoteId INT NOT NULL
        REFERENCES dbo.ClinicalNotes(NoteId),

    AuthorUserId INT NOT NULL
        REFERENCES dbo.Users(UserId),

    Content TEXT NOT NULL,

    CreatedAt TIMESTAMP NOT NULL
        DEFAULT (now() AT TIME ZONE 'utc'),

    CONSTRAINT CK_NoteAddenda_Content
        CHECK (length(btrim(Content)) > 0)
);

CREATE INDEX IF NOT EXISTS IX_NoteAddenda_Note
    ON dbo.NoteAddenda(NoteId, CreatedAt);
