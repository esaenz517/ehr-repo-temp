-- ROOM ASSIGNMENTS TABLE (Auditing Purposes, might discard later) (No seed data for the moment)
CREATE TABLE IF NOT EXISTS dbo.RoomAssignments (
    AssignmentId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RoomId       INT NOT NULL REFERENCES dbo.Rooms(RoomId),
    PatientId    INT NOT NULL REFERENCES dbo.Patients(PatientId),
    AssignedAt   TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    DischargedAt TIMESTAMP NULL --NULL means patient is still assigned to the room
);
