-- DISCIPLINES
-- The kind of clinician a person acts as inside a chart (dbo.Staff.DisciplineId).
-- DepartmentId is the department that usually trains the discipline; it is NULL
-- for disciplines with no department of their own at the university.
-- Names match the old free-text Staff.Specialization values so older data maps over.
CREATE TABLE IF NOT EXISTS dbo.Disciplines (
    DisciplineId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Code         VARCHAR(50)  NOT NULL CONSTRAINT UQ_Disciplines_Code UNIQUE,
    Name         VARCHAR(150) NOT NULL CONSTRAINT UQ_Disciplines_Name UNIQUE,
    DepartmentId INT NULL
        CONSTRAINT FK_Disciplines_Departments REFERENCES dbo.Departments(DepartmentId),
    IsActive     BOOLEAN NOT NULL DEFAULT TRUE
);

-- Seq keeps the ids in list order, matching the SQL Server database.
INSERT INTO dbo.Disciplines (Code, Name, DepartmentId)
SELECT s.Code, s.Name, d.DepartmentId
FROM (
    VALUES
        (1, 'PHARMACY',             'Pharmacy',             'PHAR'),
        (2, 'NURSE',                'Nursing',              'NURS'),
        (3, 'PHYSICAL_THERAPY',     'Physical Therapy',     'PT'),
        (4, 'OCCUPATIONAL_THERAPY', 'Occupational Therapy', 'OT'),
        (5, 'PHYSICIAN',            'Physician',            NULL),
        (6, 'PSYCHIATRY',           'Psychiatry',           NULL),
        (7, 'ALLIED_HEALTH',        'Allied Health',        NULL)
) AS s (Seq, Code, Name, DepartmentCode)
LEFT JOIN dbo.Departments d ON d.Code = s.DepartmentCode
ORDER BY s.Seq
ON CONFLICT (Code) DO NOTHING;
