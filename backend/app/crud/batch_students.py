"""
Batch Students CRUD
CSV validation and account creation for student batches.
"""

import csv
import io
import logging
import re
import secrets

from dataclasses import dataclass
from datetime import datetime, timezone

import bcrypt

from fastapi import HTTPException
from sqlalchemy import func
from sqlalchemy.orm import Session

from app.models.login import Login
from app.models.roles import Role
from app.models.staff import Staff
from app.models.user_roles import UserRole
from app.models.users import User

from app.schemas.batch_students import (
    StudentBatchResult,
    StudentBatchRow,
)

logger = logging.getLogger(__name__)

MAX_CSV_BYTES = 256 * 1024
MAX_STUDENTS = 500

# Student roles are assigned by the backend, never by the CSV.
DISCIPLINE_ROLES = {
    "nursing": "NURSE",
    "physician": "PHYSICIAN",
    "psychiatry": "PSYCHIATRY",
    "physical therapy": "PHYSICAL_THERAPY",
    "allied health": "ALLIED_HEALTH",
}

EMAIL_PATTERN = re.compile(r"^[^\s@,;]+@[^\s@,;]+\.[^\s@,;]+$")

USERNAME_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._@+-]*$")


@dataclass
class StudentData:
    row_number: int
    first_name: str
    middle_name: str | None
    last_name: str
    specialization: str
    email: str
    username: str
    result: StudentBatchRow


def parse_csv(csv_text: str) -> list[StudentData]:
    """
    Parses and validates a student CSV.
    This function does not modify the database.
    """

    if len(csv_text.encode("utf-8")) > MAX_CSV_BYTES:
        raise HTTPException(
            status_code=413,
            detail="CSV is larger than 256 KB",
        )

    reader = csv.DictReader(
        io.StringIO(csv_text.lstrip("\ufeff"), newline=""),
        strict=True,
    )

    if not reader.fieldnames:
        raise HTTPException(
            status_code=400,
            detail="CSV is empty or missing a header",
        )

    # Allow different capitalization in CSV column names.
    reader.fieldnames = [name.strip().casefold() for name in reader.fieldnames]

    headers = set(reader.fieldnames)

    if len(headers) != len(reader.fieldnames):
        raise HTTPException(
            status_code=400,
            detail="CSV contains duplicate column names",
        )

    required = {
        "firstname",
        "lastname",
        "specialization",
    }

    if not required <= headers or not (
        "email" in headers or "userprincipalname" in headers
    ):
        raise HTTPException(
            status_code=400,
            detail=(
                "CSV requires FirstName, LastName, "
                "Specialization, and Email "
                "(or UserPrincipalName) columns"
            ),
        )

    # Credentials must be generated by the server.
    password_columns = {
        "password",
        "passwordhash",
        "temppassword",
        "initialpassword",
    }

    if headers & password_columns:
        raise HTTPException(
            status_code=400,
            detail="Do not include passwords in the CSV",
        )

    parsed: list[StudentData] = []

    seen_emails: set[str] = set()
    seen_usernames: set[str] = set()

    try:
        for row in reader:

            if len(parsed) >= MAX_STUDENTS:
                raise HTTPException(
                    status_code=400,
                    detail="CSV cannot exceed 500 students",
                )

            # Ignore completely blank lines.
            if not any(str(value or "").strip() for value in row.values()):
                continue

            line = reader.line_num
            errors: list[str] = []

            if None in row:
                errors.append("Too many columns")

            def cell(key: str) -> str:
                return str(row.get(key) or "").strip()

            first = cell("firstname")
            middle = cell("middlename") or None
            last = cell("lastname")
            specialization = cell("specialization")

            email_a = cell("email").lower()
            email_b = cell("userprincipalname").lower()

            email = email_a or email_b

            username = (cell("username") or email).lower()

            if email_a and email_b and email_a != email_b:
                errors.append("Email and UserPrincipalName do not match")

            # Match existing database column lengths.
            fields = (
                ("FirstName", first, 100),
                ("LastName", last, 100),
                ("Specialization", specialization, 100),
                ("Email", email, 320),
                ("Username", username, 254),
            )

            for label, value, max_length in fields:
                if not value:
                    errors.append(f"{label} is required")
                elif len(value) > max_length:
                    errors.append(f"{label} exceeds " f"{max_length} characters")

            if middle and len(middle) > 100:
                errors.append("MiddleName exceeds 100 characters")

            full_name = " ".join(part for part in (first, middle, last) if part)

            if len(full_name) > 200:
                errors.append("Full name exceeds 200 characters")

            if email and not EMAIL_PATTERN.fullmatch(email):
                errors.append("Email is not valid")

            if username and not USERNAME_PATTERN.fullmatch(username):
                errors.append("Username contains unsupported characters")

            if email in seen_emails or username in seen_usernames:
                errors.append("Duplicate email or username in CSV")

            if email:
                seen_emails.add(email)

            if username:
                seen_usernames.add(username)

            result = StudentBatchRow(
                row_number=line,
                email=email,
                name=f"{first} {last}".strip(),
                username=username,
                status="invalid" if errors else "ready",
                message=("; ".join(errors) if errors else "Ready to create"),
            )

            parsed.append(
                StudentData(
                    row_number=line,
                    first_name=first,
                    middle_name=middle,
                    last_name=last,
                    specialization=specialization,
                    email=email,
                    username=username,
                    result=result,
                )
            )

    except csv.Error as exc:
        raise HTTPException(
            status_code=400,
            detail=f"Malformed CSV: {exc}",
        ) from exc

    if not parsed:
        raise HTTPException(
            status_code=400,
            detail="CSV has no student rows",
        )

    return parsed


def run_batch(
    db: Session,
    csv_text: str,
    validate_only: bool,
) -> StudentBatchResult:
    """
    Validates the CSV and optionally creates student accounts.

    Each student uses a separate transaction so one failed
    insert does not remove previously created accounts.
    """

    parsed = parse_csv(csv_text)

    # Resolve the existing role records.
    role_names = {"STUDENT"} | set(DISCIPLINE_ROLES.values())

    roles = {
        role.role_name: role
        for role in (
            db.query(Role)
            .filter(
                Role.role_name.in_(role_names),
                Role.is_active == True,
            )
            .all()
        )
    }

    if "STUDENT" not in roles:
        raise HTTPException(
            status_code=409,
            detail="Active STUDENT role is not configured",
        )

    # Check duplicates and required discipline roles.
    for student in parsed:

        if student.result.status != "ready":
            continue

        existing_user = (
            db.query(User.user_id)
            .filter(func.lower(User.email) == student.email)
            .first()
        )

        existing_login = (
            db.query(Login.username)
            .filter(func.lower(Login.username) == student.username)
            .first()
        )

        if existing_user or existing_login:
            student.result.status = "existing"
            student.result.message = (
                "User email or login username " "already exists; skipped"
            )
            continue

        required_role = DISCIPLINE_ROLES.get(student.specialization.casefold())

        if required_role and required_role not in roles:
            student.result.status = "invalid"
            student.result.message = f"Active role {required_role} " "is not configured"

    # Invalid input blocks all database modifications.
    blocked = any(student.result.status == "invalid" for student in parsed)

    if not validate_only and not blocked:

        for student in parsed:

            if student.result.status != "ready":
                continue

            try:
                # Generate a separate password per student.
                password = secrets.token_urlsafe(18)

                password_hash = bcrypt.hashpw(
                    password.encode("utf-8"),
                    bcrypt.gensalt(),
                ).decode("utf-8")

                full_name = " ".join(
                    part
                    for part in (
                        student.first_name,
                        student.middle_name,
                        student.last_name,
                    )
                    if part
                )

                # Create application user.
                user = User(
                    name=full_name,
                    email=student.email,
                    password_hash=None,
                    account_status="active",
                    discipline=student.specialization,
                    created_at=(datetime.now(timezone.utc).replace(tzinfo=None)),
                )

                # Create matching staff/student record.
                staff = Staff(
                    first_name=student.first_name,
                    middle_name=student.middle_name,
                    last_name=student.last_name,
                    specialization=student.specialization,
                    student=True,
                    admin=False,
                )

                db.add_all([user, staff])
                db.flush()

                # Assign the STUDENT role.
                chosen_roles = [roles["STUDENT"]]

                additional_role = DISCIPLINE_ROLES.get(
                    student.specialization.casefold()
                )

                if additional_role:
                    chosen_roles.append(roles[additional_role])

                for role in chosen_roles:
                    db.add(
                        UserRole(
                            user_id=user.user_id,
                            role_id=role.role_id,
                        )
                    )

                # Link login to both Staff and Users.
                login = Login(
                    username=student.username,
                    password_hash=password_hash,
                    staffid=staff.staffid,
                    userid=user.user_id,
                )

                db.add(login)
                db.commit()

                student.result.status = "created"
                student.result.message = "Student account created"

                student.result.staffid = staff.staffid

                # Return once for secure administrator export.
                student.result.temporary_password = password

            except Exception:
                db.rollback()

                logger.exception(
                    "Batch student import failed at CSV line %s",
                    student.row_number,
                )

                student.result.status = "failed"
                student.result.message = "Database error; student was not created"

    statuses = [student.result.status for student in parsed]

    return StudentBatchResult(
        validate_only=validate_only,
        blocked=blocked,
        ready=statuses.count("ready"),
        created=statuses.count("created"),
        existing=statuses.count("existing"),
        invalid=statuses.count("invalid"),
        failed=statuses.count("failed"),
        rows=[student.result for student in parsed],
    )
