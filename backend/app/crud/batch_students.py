"""
Batch Students CRUD
CSV validation and account creation for student batches.

Each student gets an account (dbo.Users), a person row (dbo.Staff) with the
STUDENT role, their discipline and department, and a login (dbo.T_Login).
The Discipline column takes a code or name ("NURSE" or "Nursing"); the old
Specialization column name is still accepted. Department is optional (code or
name): without it the discipline's department is used, else Interprofessional
Health Sciences (IHS).
"""

import csv
import io
import logging
import re
import secrets

from dataclasses import dataclass
from datetime import datetime, timezone

import bcrypt

from fastapi import HTTPException
from sqlalchemy import func
from sqlalchemy.orm import Session

from app.models.departments import Department
from app.models.disciplines import Discipline
from app.models.login import Login
from app.models.roles import Role
from app.models.staff import STUDENT, Staff
from app.models.users import User

from app.schemas.batch_students import (
    StudentBatchResult,
    StudentBatchRow,
)

logger = logging.getLogger(__name__)

MAX_CSV_BYTES = 256 * 1024
MAX_STUDENTS = 500

# Department used when neither the CSV nor the discipline names one.
DEFAULT_DEPARTMENT_CODE = "IHS"

EMAIL_PATTERN = re.compile(r"^[^\s@,;]+@[^\s@,;]+\.[^\s@,;]+$")

USERNAME_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._@+-]*$")


@dataclass
class StudentData:
    row_number: int
    first_name: str
    middle_name: str | None
    last_name: str
    discipline: str
    department: str | None
    email: str
    username: str
    result: StudentBatchRow


def parse_csv(csv_text: str) -> list[StudentData]:
    """
    Parses and validates a student CSV.
    This function does not modify the database.
    """

    if len(csv_text.encode("utf-8")) > MAX_CSV_BYTES:
        raise HTTPException(
            status_code=413,
            detail="CSV is larger than 256 KB",
        )

    reader = csv.DictReader(
        io.StringIO(csv_text.lstrip("\ufeff"), newline=""),
        strict=True,
    )

    if not reader.fieldnames:
        raise HTTPException(
            status_code=400,
            detail="CSV is empty or missing a header",
        )

    # Allow different capitalization in CSV column names. "Specialization" is
    # the old name of the Discipline column.
    reader.fieldnames = [
        "discipline" if name.strip().casefold() == "specialization" else name.strip().casefold()
        for name in reader.fieldnames
    ]

    headers = set(reader.fieldnames)

    if len(headers) != len(reader.fieldnames):
        raise HTTPException(
            status_code=400,
            detail="CSV contains duplicate column names",
        )

    required = {
        "firstname",
        "lastname",
        "discipline",
    }

    if not required <= headers or not (
        "email" in headers or "userprincipalname" in headers
    ):
        raise HTTPException(
            status_code=400,
            detail=(
                "CSV requires FirstName, LastName, "
                "Discipline, and Email "
                "(or UserPrincipalName) columns"
            ),
        )

    # Credentials must be generated by the server.
    password_columns = {
        "password",
        "passwordhash",
        "temppassword",
        "initialpassword",
    }

    if headers & password_columns:
        raise HTTPException(
            status_code=400,
            detail="Do not include passwords in the CSV",
        )

    parsed: list[StudentData] = []

    seen_emails: set[str] = set()
    seen_usernames: set[str] = set()

    try:
        for row in reader:

            if len(parsed) >= MAX_STUDENTS:
                raise HTTPException(
                    status_code=400,
                    detail="CSV cannot exceed 500 students",
                )

            # Ignore completely blank lines.
            if not any(str(value or "").strip() for value in row.values()):
                continue

            line = reader.line_num
            errors: list[str] = []

            if None in row:
                errors.append("Too many columns")

            def cell(key: str) -> str:
                return str(row.get(key) or "").strip()

            first = cell("firstname")
            middle = cell("middlename") or None
            last = cell("lastname")
            discipline = cell("discipline")
            department = cell("department") or None

            email_a = cell("email").lower()
            email_b = cell("userprincipalname").lower()

            email = email_a or email_b

            username = (cell("username") or email).lower()

            if email_a and email_b and email_a != email_b:
                errors.append("Email and UserPrincipalName do not match")

            # Match existing database column lengths.
            fields = (
                ("FirstName", first, 100),
                ("LastName", last, 100),
                ("Discipline", discipline, 150),
                ("Email", email, 320),
                ("Username", username, 254),
            )

            for label, value, max_length in fields:
                if not value:
                    errors.append(f"{label} is required")
                elif len(value) > max_length:
                    errors.append(f"{label} exceeds " f"{max_length} characters")

            if department and len(department) > 150:
                errors.append("Department exceeds 150 characters")

            if middle and len(middle) > 100:
                errors.append("MiddleName exceeds 100 characters")

            if email and not EMAIL_PATTERN.fullmatch(email):
                errors.append("Email is not valid")

            if username and not USERNAME_PATTERN.fullmatch(username):
                errors.append("Username contains unsupported characters")

            if email in seen_emails or username in seen_usernames:
                errors.append("Duplicate email or username in CSV")

            if email:
                seen_emails.add(email)

            if username:
                seen_usernames.add(username)

            result = StudentBatchRow(
                row_number=line,
                email=email,
                name=f"{first} {last}".strip(),
                username=username,
                status="invalid" if errors else "ready",
                message=("; ".join(errors) if errors else "Ready to create"),
            )

            parsed.append(
                StudentData(
                    row_number=line,
                    first_name=first,
                    middle_name=middle,
                    last_name=last,
                    discipline=discipline,
                    department=department,
                    email=email,
                    username=username,
                    result=result,
                )
            )

    except csv.Error as exc:
        raise HTTPException(
            status_code=400,
            detail=f"Malformed CSV: {exc}",
        ) from exc

    if not parsed:
        raise HTTPException(
            status_code=400,
            detail="CSV has no student rows",
        )

    return parsed


def run_batch(
    db: Session,
    csv_text: str,
    validate_only: bool,
) -> StudentBatchResult:
    """
    Validates the CSV and optionally creates student accounts.

    Each student uses a separate transaction so one failed
    insert does not remove previously created accounts.
    """

    parsed = parse_csv(csv_text)

    student_role = (
        db.query(Role)
        .filter(Role.role_name == STUDENT, Role.is_active == True)
        .first()
    )

    if student_role is None:
        raise HTTPException(
            status_code=409,
            detail="Active STUDENT role is not configured",
        )

    disciplines = db.query(Discipline).filter(Discipline.is_active == True).all()
    departments = db.query(Department).filter(Department.is_active == True).all()

    def find_discipline(text: str) -> Discipline | None:
        key = text.casefold()
        return next(
            (d for d in disciplines if key in (d.code.casefold(), d.name.casefold())),
            None,
        )

    def find_department(text: str) -> Department | None:
        key = text.casefold()
        return next(
            (d for d in departments if key in (d.code.casefold(), d.name.casefold())),
            None,
        )

    default_department = find_department(DEFAULT_DEPARTMENT_CODE)

    # Discipline and department ids for each ready row, by CSV line
    resolved: dict[int, tuple[int, int | None]] = {}

    # Check duplicates, disciplines, and departments.
    for student in parsed:

        if student.result.status != "ready":
            continue

        existing_user = (
            db.query(User.user_id)
            .filter(func.lower(User.email) == student.email)
            .first()
        )

        existing_login = (
            db.query(Login.username)
            .filter(func.lower(Login.username) == student.username)
            .first()
        )

        if existing_user or existing_login:
            student.result.status = "existing"
            student.result.message = (
                "User email or login username " "already exists; skipped"
            )
            continue

        discipline = find_discipline(student.discipline)

        if discipline is None:
            student.result.status = "invalid"
            student.result.message = f"Unknown discipline: {student.discipline}"
            continue

        if student.department:
            department = find_department(student.department)

            if department is None:
                student.result.status = "invalid"
                student.result.message = f"Unknown department: {student.department}"
                continue

            department_id = department.department_id
        elif discipline.department_id is not None:
            department_id = discipline.department_id
        else:
            department_id = default_department.department_id if default_department else None

        resolved[student.row_number] = (discipline.discipline_id, department_id)

    # Invalid input blocks all database modifications.
    blocked = any(student.result.status == "invalid" for student in parsed)

    if not validate_only and not blocked:

        for student in parsed:

            if student.result.status != "ready":
                continue

            try:
                # Generate a separate password per student.
                password = secrets.token_urlsafe(18)

                password_hash = bcrypt.hashpw(
                    password.encode("utf-8"),
                    bcrypt.gensalt(),
                ).decode("utf-8")

                discipline_id, department_id = resolved[student.row_number]

                # Create the account.
                user = User(
                    email=student.email,
                    password_hash=None,
                    account_status="active",
                    created_at=(datetime.now(timezone.utc).replace(tzinfo=None)),
                )

                db.add(user)
                db.flush()

                # Create the person: a student in a discipline and department.
                staff = Staff(
                    user_id=user.user_id,
                    first_name=student.first_name,
                    middle_name=student.middle_name,
                    last_name=student.last_name,
                    role_id=student_role.role_id,
                    discipline_id=discipline_id,
                    department_id=department_id,
                )

                db.add(staff)
                db.flush()

                # The login signs in to the account.
                login = Login(
                    username=student.username,
                    password_hash=password_hash,
                    userid=user.user_id,
                )

                db.add(login)
                db.commit()

                student.result.status = "created"
                student.result.message = "Student account created"

                student.result.staffid = staff.staffid

                # Return once for secure administrator export.
                student.result.temporary_password = password

            except Exception:
                db.rollback()

                logger.exception(
                    "Batch student import failed at CSV line %s",
                    student.row_number,
                )

                student.result.status = "failed"
                student.result.message = "Database error; student was not created"

    statuses = [student.result.status for student in parsed]

    return StudentBatchResult(
        validate_only=validate_only,
        blocked=blocked,
        ready=statuses.count("ready"),
        created=statuses.count("created"),
        existing=statuses.count("existing"),
        invalid=statuses.count("invalid"),
        failed=statuses.count("failed"),
        rows=[student.result for student in parsed],
    )
